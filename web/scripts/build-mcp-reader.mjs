// Generates a self-contained, version-stable MCP resource; no runtime filesystem or CDN.
import { readFile, writeFile } from 'node:fs/promises';
import ts from 'typescript';
const root = new URL('../lib/mcp/reader/', import.meta.url);
const [shell, css, source] = await Promise.all(['shell.html', 'style.css', 'client.ts'].map(name => readFile(new URL(name, root), 'utf8')));
const { outputText, diagnostics } = ts.transpileModule(source, {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.None, strict: true },
  fileName: 'client.ts', reportDiagnostics: true,
});
if (diagnostics?.length) throw new Error(ts.formatDiagnosticsWithColorAndContext(diagnostics, {
  getCanonicalFileName: f => f, getCurrentDirectory: () => process.cwd(), getNewLine: () => '\n',
}));
const html = shell.replace('/* READER_CSS */', () => css).replace('/* READER_JS */', () => outputText.replace(/<\/script/gi, '<\\/script'));
const generated = '// Generated by scripts/build-mcp-reader.mjs. Edit reader/client.ts, style.css, shell.html.\nexport const readerHtml = ' + JSON.stringify(html) + ';\n';
const target = new URL('generated.ts', root);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== generated) throw new Error('Reader resource is stale. Run node scripts/build-mcp-reader.mjs.');
} else await writeFile(target, generated);
